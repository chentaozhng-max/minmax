/**
 * 范围分类器端口 —— 领域层对「怎么判断话题范围」的抽象。
 *
 * ## 为什么要有这一层
 *
 * 领域层（`scope-guard.ts` 的判定逻辑、应用层编排）不该知道背后是大模型、
 * 小模型、还是某个第三方内容审核 API。它只知道「给一句话，拿一个 verdict」。
 *
 * 将来换实现（换成更便宜的模型 / 规则引擎 / 云厂商审核接口）只写一个新
 * 适配器，本文件与所有调用方一行不动。
 *
 * ## 关于「本期用主模型」
 *
 * 二二定的：先用主模型，但**做好定义**，未来可以换。所以这一层不是过度设计，
 * 是给「未来换」留的那个接缝 —— 配置里 `SCOPE_MODEL` 走环境变量，
 * 换模型不用改代码。
 *
 * ## 契约：实现必须自己吞掉所有异常
 *
 * `classify()` **不允许抛异常**。超时、网络错误、JSON 解析失败，全部由
 * 实现方捕获并返回 `IN_SCOPE`（放行）。理由：这一层是体验优化，
 * 分类器挂了把用户挡在门外，是拿体验换一个本来就不该靠它保证的东西。
 * 让异常漏上去还会导致整轮对话失败 —— 那是把「少省一次调用」升级成「用不了」。
 */
import type { ScopeVerdict } from "@/domain/scope-guard";

export interface ScopeClassifier {
  /**
   * 是否可用。每次调用都重新判断，不要缓存 ——
   * 否则测试里改环境变量会失效（这条约定与 LlmPort.configured 一致）。
   */
  configured(): boolean;

  /**
   * 判一句话的范围。
   *
   * @returns 永远返回一个 verdict，不抛异常。任何失败都必须降级成 IN_SCOPE。
   */
  classify(text: string): Promise<ScopeVerdict>;
}
